import { expect, test } from '@playwright/test';
import { formatMoney } from '../../apps/web/src/money';
test('compact HUD and outcome preserve actual result values and narrow retry access', async ({ page }, info) => {
  await page.addInitScript(() => localStorage.setItem('stack-and-survive.nickname', 'SavedPlayer'));
  await page.goto('/?tycoon'); await page.getByRole('button', { name: 'Start Game' }).click();
  await expect(page.getByRole('button', { name: 'Ⅱ Pause', exact: true })).toBeEnabled({ timeout: 20000 });
  const hud = page.getByRole('region', { name: 'Business status' });
  await expect(hud.getByRole('meter')).toHaveCount(0);
  await expect(hud).toContainText('Upgrade Funds'); await expect(hud).toContainText('Availability');
  await page.getByText('Tycoon QA', { exact: true }).click();
  while (Number(await page.getByTestId('elapsed').textContent()) < 45) await page.getByRole('button', { name: 'Step one tick', exact: true }).click();
  const result = page.getByRole('region', { name: 'Business result' });
  await expect(result).toContainText('App Service Saturation'); await expect(result).toContainText('Score 810');
  await expect(result.getByRole('button', { name: 'Play again' })).toBeFocused();
  await expect(page.getByRole('button', { name: 'Zoom in', exact: true })).toHaveCount(0);
  await expect(page.getByRole('region', { name: 'World guide' })).toHaveCount(0);
  await expect(page.locator('.tycoon-header')).toHaveJSProperty('inert', true);
  await expect(page.getByTestId('world')).toHaveJSProperty('inert', true);
  await result.getByRole('button', { name: 'Review business' }).focus(); await page.keyboard.press('Tab');
  await expect(result.getByRole('button', { name: 'Change for future runs', exact: true })).toBeFocused();
  await page.keyboard.press('Shift+Tab'); await expect(result.getByRole('button', { name: 'Review business' })).toBeFocused();
  await result.getByRole('button', { name: 'Change for future runs', exact: true }).click();
  const nickname = result.getByRole('textbox', { name: 'Player name', exact: true });
  await expect(nickname).toBeFocused();
  await page.keyboard.press('Shift+Tab'); await expect(result.getByRole('button', { name: 'Review business' })).toBeFocused();
  await page.keyboard.press('Tab'); await expect(nickname).toBeFocused();
  await nickname.fill('ReviewUser'); await result.getByRole('button', { name: 'Save name', exact: true }).click();
  const state = JSON.parse((await page.getByTestId('diagnostics').textContent())!);
  await expect(result.getByRole('region', { name: 'Architecture profile' })).toHaveCount(0);
  await result.getByText('Details · decisions, tradeoffs & records', { exact: true }).click();
  await expect(result).toContainText(formatMoney(state.result.economy.netBusinessValue));
  await expect(result.getByRole('region', { name: 'Architecture profile' })).toBeVisible();
  await result.getByText('Details · decisions, tradeoffs & records', { exact: true }).click();
  for (const width of [320,390,1024,1440,1920]) {
    await page.setViewportSize({ width, height: 740 });
    const rect = (await result.boundingBox())!;
    expect(rect.x).toBeGreaterThanOrEqual(0); expect(rect.x+rect.width).toBeLessThanOrEqual(width);
    expect(rect.y).toBeGreaterThanOrEqual(0); expect(rect.y+rect.height).toBeLessThanOrEqual(740);
    const retry = (await result.getByRole('button', { name: 'Play again', exact: true }).boundingBox())!;
    expect(retry.y).toBeGreaterThanOrEqual(0); expect(retry.y + retry.height).toBeLessThanOrEqual(740);
    expect(retry.height).toBeGreaterThanOrEqual(44);
    await result.getByRole('button', { name: 'Play again', exact: true }).click({ trial: true });
    expect(await result.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath(`operation-report-${width}.png`) });
  }
  await page.screenshot({ path: info.outputPath('game-outcome.png') });
  await result.getByRole('button', { name: 'Review business' }).click();
  await expect(page.getByRole('dialog')).toContainText('Write capacity 70/s');
  await page.keyboard.press('Escape'); await expect(result.getByRole('button', { name: 'Review business' })).toBeFocused();
  await result.getByRole('button', { name: 'Play again' }).focus(); await page.keyboard.press('Enter'); await expect(page.getByRole('button', { name: 'Start Game' })).toBeFocused();
});
